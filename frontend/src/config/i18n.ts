export type Language = keyof typeof dictionary;
export type TKey = keyof (typeof dictionary)['en'];

export const languages: { value: Language; label: string }[] = [
  { value: 'en', label: 'English' },
  { value: 'th', label: 'ไทย' },
];

/** Replaces {name} placeholders. Missing Thai keys fall back to English. */
export function translate(
  language: Language,
  key: TKey,
  vars?: Record<string, string | number>,
): string {
  const table = dictionary[language] as Record<string, string>;
  let text = table[key] ?? dictionary.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
